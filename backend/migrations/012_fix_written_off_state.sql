-- 012_fix_written_off_state.sql
--
-- Виправлення даних: 4 позиції зі станом `written_off`, які не мають
-- жодного запису в журналі пошкоджень.
--
-- Рішення власника від 2026-09-06. Повне обґрунтування, докази й таблиця
-- фактів: `audit/DATA_ANOMALIES.md`, розділ A-2.
--
-- ЧОМУ ЦЕ ДЕФЕКТ ДАНИХ, А НЕ ЛОГІКИ
-- ---------------------------------------------------------------------------
-- `state = 'written_off'` виставляється єдиним місцем у коді
-- (`damage_cases.py:137`) і завжди РАЗОМ зі створенням запису в
-- `product_damage_history`. Списання без запису в журналі технічно
-- неможливе, тому для цих рядків стан не має джерела походження.
-- Решта полів тих самих товарів каже, що товар живий: `quantity > 0`,
-- `frozen_quantity = 0`, `in_laundry = 0`, `status = 1` (видимий у каталозі),
-- у трьох із чотирьох `product_state = 'shelf'` — «лежить на полиці».
--
-- ЦІЛЬОВЕ ЗНАЧЕННЯ
-- ---------------------------------------------------------------------------
-- `available`. Еталон узятий з позицій, які журнал МАЮТЬ: після завершеної
-- обробки стан повертається у `available` (234 записи з
-- `processing_status = 'completed'`). Це ж і домінантний стан каталогу
-- (7917 із 8200 товарів).
--
-- ЧОГО ЦЯ МІГРАЦІЯ СВІДОМО НЕ РОБИТЬ
-- ---------------------------------------------------------------------------
-- * НЕ змінює `products.quantity`. При списанні `damage_cases.py` уже
--   виконує `quantity = quantity - :qty`, тому склад актуальний. Повторне
--   віднімання створило б недостачу з нічого. Це пряма вимога власника.
-- * НЕ змінює `frozen_quantity`, `in_laundry`, `status`, `product_state`.
-- * НЕ створює записів у `product_damage_history`: події не було, і
--   вигадувати її в журналі означало б фальсифікувати історію.
-- * НЕ чіпає 7 позицій `written_off`, які журнал мають — там стан
--   обґрунтований і є коректним.
-- * НЕ чіпає замовлення №7970 (аномалія A-1): за канонічним правилом
--   архівний ордер резерв не тримає, тому на доступність воно не впливає,
--   а `notes` доводять, що це операційна помилка статусу.
--
-- ВПЛИВ НА ДОСТУПНІСТЬ: НУЛЬОВИЙ
-- ---------------------------------------------------------------------------
-- Канонічне правило `STATE_AFFECTS_AVAILABILITY = False` виключає
-- `products.state` з формули (`services/availability/rules.py`). Тому жодна
-- цифра доступності не змінюється. Виправлення знімає хибний сигнал в
-- складських екранах — і не може нічого зламати в продажі за побудовою.
--
-- САМОПЕРЕВІРКА
-- ---------------------------------------------------------------------------
-- `WHERE` містить не лише ID, а всі умови-докази, за якими рядок був
-- класифікований як дефект. Якщо після заведення реєстру товар списали
-- по-справжньому (з'явився запис у журналі) або кількість обнулилася —
-- умова не виконається і рядок лишиться недоторканим. Міграція не може
-- зачепити запис, стан якого змінився.

UPDATE products
SET state = 'available'
WHERE product_id IN (249, 2335, 2675, 4046)
  AND state = 'written_off'
  AND quantity > 0
  AND COALESCE(frozen_quantity, 0) = 0
  AND COALESCE(in_laundry, 0) = 0
  AND NOT EXISTS (
      SELECT 1
      FROM product_damage_history pdh
      WHERE pdh.product_id = products.product_id
  );