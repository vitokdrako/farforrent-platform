def statuses_placeholder(prefix: str, statuses: tuple) -> tuple:
    """
    Побудувати безпечний список плейсхолдерів для `IN (...)`.

    Значення беруться лише з констант цього модуля, тому підстановка
    рядків у SQL неможлива; параметри все одно передаються біндами.

    Returns:
        (sql_fragment, params_dict) — наприклад ("(:st0, :st1)", {...})
    """
    keys = [f"{prefix}{i}" for i in range(len(statuses))]
    fragment = "(" + ", ".join(f":{k}" for k in keys) + ")"
    params = {k: v for k, v in zip(keys, statuses)}
    return fragment, params